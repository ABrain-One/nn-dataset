import torch
import torch.nn as nn

def supported_hyperparameters():
    return {'lr', 'momentum'}

class Block(nn.Module):
    def __init__(self, in_channels, out_channels, stride=1):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size=3, stride=stride, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.conv(x)

    def fuse_conv_bn(self):
        # Fuse Conv and BN for optimization
        fused = (self.conv[0].weight / torch.sqrt(self.conv[0].weight.var() + 1e-5)) \
                * self.conv[0].bias + self.conv[1].running_mean
        return nn.Conv2d(self.conv[0].in_channels,
                         self.conv[0].out_channels,
                         kernel_size=self.conv[0].kernel_size,
                         stride=self.conv[0].stride,
                         padding=self.conv[0].padding).to(self.conv[0].weight.device).float().requires_grad_(False).to(x.device)

    def switch_to_deploy(self):
        fused_conv = self.fuse_conv_bn()
        self.__class__ = nn.Conv2d
        self.in_channels = fused_conv.in_channels
        self.out_channels = fused_conv.out_channels
        self.kernel_size = fused_conv.kernel_size
        self.stride = fused_conv.stride
        self.padding = fused_conv.padding
        self.weight = fused_conv.weight
        self.bias = fused_conv.bias

class Net(nn.Module):
    def __init__(self, in_shape, out_shape, prm, device):
        super().__init__()
        self.device = device
        self.in_channels = in_shape[1] if len(in_shape) == 4 else in_shape[0]  # derive from in_shape
        num_classes = int(out_shape[0])
        self.stem = nn.Sequential(
            nn.Conv2d(self.in_channels, 32, kernel_size=3, stride=1, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=2, stride=2, padding=0)
        )
        self.block1 = Block(32, 64, stride=1)
        self.block2 = Block(64, 128, stride=2)
        self.block3 = Block(128, 256, stride=2)
        self.block4 = Block(256, 512, stride=2)
        self.avgpool = nn.AdaptiveAvgPool2d((6, 6))
        self.classifier = nn.Linear(512 * 6 * 6, num_classes)

    def forward(self, x):
        x = self.stem(x)
        x = self.block1(x)
        x = self.block2(x)
        x = self.block3(x)
        x = self.block4(x)
        x = self.avgpool(x)
        x = x.flatten(1)
        x = self.classifier(x)
        return x

    def train_setup(self, prm):
        self.to(self.device)
        self.optimizer = torch.optim.SGD(
            self.parameters(),
            lr=prm.get('lr', 0.01),
            momentum=prm.get('momentum', 0.9),
        )
        self.criteria = (nn.CrossEntropyLoss().to(self.device),)

    def learn(self, train_data):
        self.train()
        for inputs, labels in train_data:
            inputs, labels = inputs.to(self.device), labels.to(self.device)
            self.optimizer.zero_grad()
            outputs = self(inputs)
            loss = self.criteria[0](outputs, labels)
            loss.backward()
            self.optimizer.step()