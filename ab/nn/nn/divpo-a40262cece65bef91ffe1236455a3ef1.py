class Block(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, stride=1, padding=1):
        super().__init__()
        self.conv = nn.Conv2d(in_channels, out_channels, kernel_size=kernel_size, stride=stride, padding=padding)
        self.bn = nn.BatchNorm2d(out_channels)
        self.relu = nn.ReLU(inplace=True)

    def forward(self, x):
        return self.relu(self.bn(self.conv(x)))

    def fuse(self):
        # Fused block for edge-friendly deployment
        if isinstance(self.conv, nn.Conv2d) and isinstance(self.bn, nn.BatchNorm2d):
            fused_conv = nn.Conv2d(
                in_channels=self.conv.in_channels,
                out_channels=self.conv.out_channels,
                kernel_size=self.conv.kernel_size,
                stride=self.conv.stride,
                padding=self.conv.padding,
                bias=False
            ).requires_grad_(False)

            fused_conv.weight.copy_(self.conv.weight)
            if self.conv.bias is not None:
                bias = self.conv.bias.requires_grad_(False)
                fused_conv.bias.copy_(self.conv.bias)

            # BatchNorm2d is already fused into Conv2d in this case
            bn_weight = self.bn.weight.requires_grad_(False)
            bn_bias = self.bn.bias.requires_grad_(False)
            bn_running_mean = self.bn.running_mean.requires_grad_(False)
            bn_running_var = self.bn.running_var.requires_grad_(False)

            fused_conv.weight.mul_(bn_weight.reshape(1, -1, 1, 1))
            if fused_conv.bias is not None:
                fused_conv.bias.addmm_(bn_bias, bn_running_mean, beta=1, alpha=bn_weight.reciprocal())
                fused_conv.bias.mul_(bn_weight.reciprocal())
                fused_conv.bias.add_(bn_bias - bn_running_var * bn_weight.square())

            self.__class__ = nn.Conv2d
            self.in_channels = fused_conv.in_channels
            self.out_channels = fused_conv.out_channels
            self.kernel_size = fused_conv.kernel_size
            self.stride = fused_conv.stride
            self.padding = fused_conv.padding
            self.weight = fused_conv.weight
            if fused_conv.bias is not None:
                self.bias = fused_conv.bias
        else:
            print("Fused block can only be applied to Conv2d + BatchNorm2d")

