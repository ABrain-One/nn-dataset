# Ensure the total parameter count does not exceed the limit
def get_parameter_count(m):
    return sum(p.numel() for p in m.parameters())

def replace_block_with_edgeblock(m, block_class):
    if isinstance(m, block_class):
        edge_blocks = [
            EdgeBlock(m.conv.in_channels, m.conv.out_channels, m.conv.kernel_size, m.conv.stride, m.conv.padding, m.conv.groups),
            EdgeBlock(m.bn.running_mean.numel(), m.bn.running_var.numel(), m.conv.kernel_size, m.conv.stride, m.conv.padding, m.conv.groups)
        ]
        return edge_blocks
    for child_module in m.children():
        return replace_block_with_edgeblock(child_module, block_class)
    return []

# Replace all blocks in the model with EdgeBlock to ensure parameter count does not exceed the limit
edge_blocks = replace_block_with_edgeblock(Net([3, 32, 32], [10, 1], {}, torch.device('cpu')), Block)
total_params = get_parameter_count(Net([3, 32, 32], [10, 1], {}, torch.device('cpu'))) + sum(get_parameter_count(block) for block in edge_blocks)
