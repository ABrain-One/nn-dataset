import torch
import torch.nn as nn

def supported_hyperparameters():
    return {'lr', 'momentum'}

class Net(nn.Module):
    def __init__(self, in_shape, out_shape, prm, device):
        super().__init__()
        self.device = device
        self.in_channels = in_shape[1]
        self.num_classes = out_shape[0]
        self.learning_rate = prm.get('lr', 0.01)
        self.momentum = prm.get('momentum', 0.9)
        self.features = self.build_features()
        self.avgpool = nn.AdaptiveAvgPool2d((1, 1))
        self.classifier = nn.Linear(self._last_channels, self.num_classes)

    def build_features(self):
        layers = []
        layers += [
            nn.Conv2d(self.in_channels, 32, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
        ]
        layers += [
            nn.Conv2d(32, 32, kernel_size=3, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
        ]
        self._last_channels = 32
        return nn.Sequential(*layers)

    def forward(self, x):
        x = self.features(x)
        x = self.avgpool(x)
        x = torch.flatten(x, 1)
        return self.classifier(x)

    def train_setup(self, prm):
        self.to(self.device)
        self.criteria = nn.CrossEntropyLoss().to(self.device)
        self.optimizer = torch.optim.SGD(
            self.parameters(),
            lr=self.learning_rate,
            momentum=self.momentum
        )

    def learn(self, train_data):
        self.train()
        for inputs, labels in train_data:
            inputs, labels = inputs.to(self.device), labels.to(self.device)
            self.optimizer.zero_grad()
            outputs = self(inputs)
            loss = self.criteria(outputs, labels)
            loss.backward()
            self.optimizer.step()

def check_shape(shape):
    in_channels, height, width = shape
    assert 3 <= height <= 64, height
    assert 3 <= width <= 64, width

def get_workspace_size(shape):
    check_shape(shape)
    return 32

def get_next_multiple(x, base=32):
    return (x + base - 1) // base * base

class NetWithSpace(Net):
    def __init__(self, in_shape, out_shape, prm, device):
        workspace_size = get_workspace_size(in_shape)
        workspace_height = get_next_multiple(workspace_size, base=64)
        workspace_shape = (in_shape[1], workspace_height, workspace_height)
        super().__init__(workspace_shape, out_shape, prm, device)

    def build_features(self):
        workspace_height = get_next_multiple(self.in_channels, base=64)
        workspace_shape = (self.in_channels, workspace_height, workspace_height)
        layers = [
            nn.Conv2d(self.in_channels, 32, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=2, stride=2),
            nn.Conv2d(32, 32, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
            nn.AdaptiveAvgPool2d((workspace_height, workspace_height)),
        ]
        self._last_channels = 32
        return nn.Sequential(*layers)

    def learn(self, train_data):
        # Provided train_data is already preprocessed to fit workspace_size,
        # so no need to resize inputs in learn()
        super().learn(train_data)

