import torch
import torch.nn as nn

def supported_hyperparameters():
    return {'lr', 'momentum'}

class Block(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size=3, stride=1, padding=1):
        super().__init__()
        self.conv = nn.Conv2d(in_channels, out_channels, kernel_size=kernel_size, stride=stride, padding=padding)
        self.bn = nn.BatchNorm2d(out_channels)
        self.relu = nn.ReLU(inplace=True)

    def forward(self, x):
        return self.relu(self.bn(self.conv(x)))

    def fuse(self):
        # Fused block for edge-friendly deployment
        if self.conv.weight.requires_grad:
            fused_weight = nn.Parameter(self.conv.weight.data.clone())
            bias = self.conv.bias
            assert bias is not None
            nn.init.constant_(fused_weight, 0)
            self.conv = nn.Conv2d(self.conv.in_channels, self.conv.out_channels,
                                  kernel_size=self.conv.kernel_size,
                                  stride=self.conv.stride,
                                  padding=self.conv.padding,
                                  groups=self.conv.groups,
                                  bias=False)
            self.conv.weight.data.copy_(fused_weight)
            self.bn = nn.BatchNorm2d(self.conv.out_channels,
                                     eps=self.bn.eps,
                                     momentum=self.bn.momentum)
            self.bn.weight.data.copy_(self.bn.running_mean)
            self.bn.bias.data.copy_(self.bn.running_var)
            if self.bn.affine:
                self.bn.weight.data.zero_().add_(1)
                self.bn.bias.data.copy_(bias)
            self.bn.training = True
            self.bn.track_running_stats = True
            self.bn.running_mean.copy_(self.bn.running_var)
            self.bn.running_var.zero_()
            self.bn.num_batches_tracked.zero_()
            self.relu = None

class Net(nn.Module):
    def __init__(self, in_shape, out_shape, prm, device):
        super().__init__()
        self.device = device
        in_channels = in_shape[1]  # channels-first (C, H, W)
        num_classes = int(out_shape[0])
        self.stem = nn.Conv2d(in_channels, 32, kernel_size=3, stride=1, padding=1)
        self.block1 = Block(32, 32, stride=1)
        self.block2 = Block(32, 64, stride=2)
        self.block3 = Block(64, 128, stride=2)
        self.avgpool = nn.AdaptiveAvgPool2d((6, 6))
        self.classifier = nn.Linear(128 * 6 * 6, num_classes)
        self.criteria = nn.CrossEntropyLoss().to(device)
        self.optimizer = torch.optim.SGD(
            self.parameters(),
            lr=prm.get('lr', 0.01),
            momentum=prm.get('momentum', 0.9),
        )

    def forward(self, x):
        x = self.stem(x)
        x = self.block1(x)
        x = self.block2(x)
        x = self.block3(x)
        x = self.avgpool(x)
        x = x.flatten(1)
        x = self.classifier(x)
        return x

    def train_setup(self, prm):
        self.to(self.device)
        self.criteria = nn.CrossEntropyLoss().to(self.device)
        self.optimizer = torch.optim.SGD(
            self.parameters(),
            lr=prm.get('lr', 0.01),
            momentum=prm.get('momentum', 0.9),
        )

    def learn(self, train_data):
        self.train()
        for inputs, labels in train_data:
            inputs, labels = inputs.to(self.device), labels.to(self.device)
            self.optimizer.zero_grad()
            outputs = self(inputs)
            loss = self.criteria(outputs, labels)
            loss.backward()
            self.optimizer.step()

    def export(self):
        # Fuse BatchNorm for improved inference performance
        for mod in self.modules():
            if isinstance(mod, Block):
                mod.fuse()
        return self

