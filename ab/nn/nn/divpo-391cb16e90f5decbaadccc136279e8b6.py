def get_flops(model, input_size):
    flops = 0
    for m in model.modules():
        if isinstance(m, (nn.Conv2d, nn.Linear)):
            if m is not model.stem[-1] and m is not model.classifier[-1]:
                flops += m.in_channels * m.out_channels * m.kernel_size