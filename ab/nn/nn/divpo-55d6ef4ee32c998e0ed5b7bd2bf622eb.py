class InvertedResidual(nn.Module):
    def __init__(self, in_channels, out_channels, stride, expand_ratio):
        super(InvertedResidual, self).__init__()
        self.stride = stride
        self.use_res_connect = self.stride == 1 and in_channels == out_channels

        layers = []
        if expand_ratio != 1:
            layers.append(
                nn.Conv2d(in_channels, in_channels * expand_ratio, 1, 1, 0, bias=False))
            layers.append(nn.BatchNorm2d(in_channels * expand_ratio))
            layers.append(nn.ReLU6(inplace=True))
        layers.extend([
            nn.Conv2d(
                in_channels * expand_ratio,
                in_channels * expand_ratio,
                kernel_size=3,
                stride=stride,
                padding=1,
                groups=in_channels * expand_ratio,
                bias=False),
            nn.BatchNorm2d(in_channels * expand_ratio),
            nn.ReLU6(inplace=True),
            nn.Conv2d(in_channels * expand_ratio, out_channels, 1, 1, 0, bias=False),
            nn.BatchNorm2d(out_channels),
        ])
        self.conv = nn.Sequential(*layers)

    def forward(self, x):
        if self.use_res_connect:
            return x + self.conv(x)
        else:
            return self.conv(x)